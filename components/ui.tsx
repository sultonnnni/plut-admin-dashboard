export type IconName = keyof typeof PATHS;

export function Icon({ name, className = "h-5 w-5" }: { name: IconName; className?: string }) {
  return (
    <svg className={className} fill="none" viewBox="0 0 24 24" strokeWidth={1.5} stroke="currentColor" aria-hidden="true">
      <path strokeLinecap="round" strokeLinejoin="round" d={PATHS[name]} />
    </svg>
  );
}

/** Foto produk; bila gagal dimuat tampil ikon placeholder. */
export function Thumb({ path, name, size = "h-12 w-12" }: { path?: string | null; name: string; size?: string }) {
  const [failed, setFailed] = useState(false);
  const src = imageUrl(path);

  useEffect(() => {
    setFailed(false);
  }, [src]);

  if (!src || failed) {
    return (
      <div className={size + " flex shrink-0 items-center justify-center rounded-lg bg-slate-100 text-slate-400"}>
        <Icon name="photo" className="h-5 w-5" />
      </div>
    );
  }
  // eslint-disable-next-line @next/next/no-img-element
  return <img src={src} alt={name} onError={() => setFailed(true)} className={size + " shrink-0 rounded-lg object-cover ring-1 ring-slate-200"} />;
}

const BADGE_STYLE: Record<string, string> = {
  "Best Seller": "bg-amber-50 text-amber-700 ring-amber-600/20",
  "Pilihan Kurator": "bg-violet-50 text-violet-700 ring-violet-600/20",
  "Produk Unggulan": "bg-emerald-50 text-emerald-700 ring-emerald-600/20",
};

export function BadgePill({ badge }: { badge: string }) {
  return (
    <span
      className={
        "inline-flex items-center rounded-full px-2.5 py-0.5 text-xs font-medium ring-1 ring-inset " +
        (BADGE_STYLE[badge] ?? "bg-slate-50 text-slate-600 ring-slate-500/20")
      }
    >
      {badge || "-"}
    </span>
  );
}

export function StockPill({ stock }: { stock: number }) {
  const low = stock <= LOW_STOCK;
  return (
    <span
      className={
        "inline-flex items-center gap-1 rounded-full px-2.5 py-0.5 text-xs font-medium ring-1 ring-inset " +
        (low ? "bg-red-50 text-red-700 ring-red-600/20" : "bg-slate-50 text-slate-700 ring-slate-500/20")
      }
    >
      {low && <Icon name="warn" className="h-3.5 w-3.5" />}
      {stock}
    </span>
  );
}